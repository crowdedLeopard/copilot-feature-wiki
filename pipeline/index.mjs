#!/usr/bin/env node
/** Index: regenerate wiki/index.md (the catalogue the model and humans read first) and data/stats.json. */
import fs from 'node:fs/promises';
import path from 'node:path';
import { loadPages, loadConcepts } from './lib/pages.mjs';
import { WIKI_DIR, DATA_DIR, writeJson, appendLog, today, readJson } from './lib/util.mjs';
import { DESKS, ACTION } from '../config/taxonomy.mjs';

async function main() {
  const pages = (await loadPages()).filter((p) => !p.error && p.data.title);
  const concepts = (await loadConcepts()).filter((p) => !p.error && p.data.title);
  const catalog = await readJson(path.join(DATA_DIR, 'catalog.json'), { items: [] });
  const lines = [
    '# Index', '',
    `Catalogue of every page in the wiki. Regenerated by \`npm run index:wiki\` on ${today()}. ${pages.length} briefings, ${concepts.length} concepts; ${catalog.items.length} roadmap items tracked.`, '',
  ];
  for (const desk of DESKS) {
    const mine = pages.filter((p) => p.data.desk === desk.id).sort((a, b) => (ACTION[b.data.action]?.rank ?? 0) - (ACTION[a.data.action]?.rank ?? 0) || a.data.title.localeCompare(b.data.title));
    if (!mine.length) continue;
    lines.push(`## ${desk.label} (${mine.length})`, '');
    for (const p of mine) {
      lines.push(`- [${p.data.title}](features/${p.slug}.md) · ${p.data.status} · risk ${p.data.risk} · cost ${p.data.cost} · ${ACTION[p.data.action]?.label ?? p.data.action}. ${p.data.summary}`);
    }
    lines.push('');
  }
  if (concepts.length) {
    lines.push(`## Concepts (${concepts.length})`, '');
    for (const c of concepts) lines.push(`- [${c.data.title}](concepts/${c.slug}.md). ${c.data.summary || ''}`);
    lines.push('');
  }
  await fs.writeFile(path.join(WIKI_DIR, 'index.md'), lines.join('\n'));
  const stats = {
    generated: new Date().toISOString(), briefings: pages.length, concepts: concepts.length, tracked: catalog.items.length,
    byDesk: Object.fromEntries(DESKS.map((d) => [d.id, pages.filter((p) => p.data.desk === d.id).length])),
    actNow: pages.filter((p) => p.data.action === 'act-now').length,
    updatedThisWeek: pages.filter((p) => (Date.now() - new Date(p.data.updated)) < 7 * 86400000).length,
  };
  await writeJson(path.join(DATA_DIR, 'stats.json'), stats);
  const line = `- ${today()} index: ${pages.length} briefings, ${concepts.length} concepts indexed`;
  await appendLog(line);
  console.log(line);
}

main().catch((err) => { console.error(err); process.exit(1); });
