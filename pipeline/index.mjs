#!/usr/bin/env node
/** Index: regenerate wiki/index.md (the catalogue the model and humans read first) and data/stats.json. */
import fs from 'node:fs/promises';
import path from 'node:path';
import { loadPages, loadConcepts } from './lib/pages.mjs';
import { WIKI_DIR, DATA_DIR, writeJson, appendLog, today, readJson } from './lib/util.mjs';
import { TOPICS, ACTION, VERIFICATION } from '../config/taxonomy.mjs';
import { listHeld, verificationDue } from './lib/verify.mjs';
import { loadSources, sourceChangesByPage } from './lib/sources.mjs';
import { loadMessageIndex } from './lib/message-center.mjs';

async function main() {
  const everything = (await loadPages()).filter((p) => !p.error && p.data.title);
  const pages = everything.filter((p) => !p.data.archived);
  const archived = everything.filter((p) => p.data.archived).sort((a, b) => b.data.archived.date.localeCompare(a.data.archived.date));
  const concepts = (await loadConcepts()).filter((p) => !p.error && p.data.title);
  const catalog = await readJson(path.join(DATA_DIR, 'catalog.json'), { items: [] });
  const messages = await loadMessageIndex();
  const briefedIds = new Set(pages.map((p) => p.data.roadmapId).filter(Boolean));
  const deadlines = (messages.posts || []).filter((m) => m.actionRequiredBy && m.actionRequiredBy.slice(0, 10) >= today()).sort((a, b) => a.actionRequiredBy.localeCompare(b.actionRequiredBy));
  const lines = [
    '# Index', '',
    `Catalogue of every page in the wiki. Regenerated by \`npm run index:wiki\` on ${today()}. ${pages.length} briefings, ${archived.length} archived, ${concepts.length} concepts; ${catalog.items.length} roadmap items tracked.`, '',
  ];
  for (const topic of TOPICS) {
    const mine = pages.filter((p) => p.data.topic === topic.id).sort((a, b) => (ACTION[b.data.action]?.rank ?? 0) - (ACTION[a.data.action]?.rank ?? 0) || a.data.title.localeCompare(b.data.title));
    if (!mine.length) continue;
    lines.push(`## ${topic.label} (${mine.length})`, '');
    for (const p of mine) {
      lines.push(`- [${p.data.title}](features/${p.slug}.md) · ${p.data.status} · risk ${p.data.risk} · cost ${p.data.cost} · ${ACTION[p.data.action]?.label ?? p.data.action}. ${p.data.summary}`);
    }
    lines.push('');
  }
  // Message Center deadlines, so the catalogue says what has a date on it. The posts themselves are under raw/message-center.
  if (deadlines.length) {
    lines.push(`## Message Center act-by dates (${deadlines.length})`, '', `Dates Microsoft has set in Message Center posts. ${messages.count} posts are stored under raw/message-center.`, '');
    for (const m of deadlines) {
      const briefed = (m.roadmapIds || []).filter((id) => briefedIds.has(id));
      lines.push(`- ${m.actionRequiredBy.slice(0, 10)} · ${m.id} · ${m.title}${m.roadmapIds?.length ? ` (roadmap ${m.roadmapIds.join(', ')}${briefed.length ? ', briefed' : ', not yet briefed'})` : ''}`);
    }
    lines.push('');
  }
  if (concepts.length) {
    lines.push(`## Concepts (${concepts.length})`, '');
    for (const c of concepts) lines.push(`- [${c.data.title}](concepts/${c.slug}.md). ${c.data.summary || ''}`);
    lines.push('');
  }
  // Pages the verifier is holding back are not published; the index says so, with the reason, so they are not forgotten.
  const held = await listHeld();
  const sources = await loadSources();
  const sourceChanges = sourceChangesByPage(sources);
  if (held.length) {
    lines.push(`## Held for correction (${held.length})`, '', 'Not published. Each failed its independent check against Microsoft Learn, or has not had one yet, and is queued for the writer with the verifier\'s findings.', '');
    for (const h of held) lines.push(`- [${h.data.title}](_held/${h.slug}.md) · ${h.report?.hold?.reason || 'unverified'}${h.report?.hold?.since ? ` since ${h.report.hold.since}` : ''}. ${(h.report?.hold?.reasons || []).join('; ')}`);
    lines.push('');
  }
  if (archived.length) {
    lines.push(`## Archive (${archived.length})`, '', 'Briefings whose roadmap item was cancelled or left the roadmap. Kept for reference, not for action.', '');
    for (const p of archived) lines.push(`- [${p.data.title}](features/${p.slug}.md) · archived ${p.data.archived.date} (${p.data.archived.reason === 'cancelled' ? 'cancelled by Microsoft' : 'left the roadmap'}). ${p.data.summary}`);
    lines.push('');
  }
  await fs.writeFile(path.join(WIKI_DIR, 'index.md'), lines.join('\n'));
  const stats = {
    generated: new Date().toISOString(), briefings: pages.length, archived: archived.length, concepts: concepts.length, tracked: catalog.items.length,
    byTopic: Object.fromEntries(TOPICS.map((t) => [t.id, pages.filter((p) => p.data.topic === t.id).length])),
    actNow: pages.filter((p) => p.data.action === 'act-now').length,
    updatedThisWeek: pages.filter((p) => (Date.now() - new Date(p.data.updated)) < 7 * 86400000).length,
    verification: {
      checked: pages.filter((p) => ['verified', 'verified-with-gaps'].includes(p.data.verification?.status)).length,
      needsCorrection: pages.filter((p) => p.data.verification?.status === 'needs-correction').length,
      unchecked: pages.filter((p) => !p.data.verification).length,
      held: held.length,
      // Pages whose check is due again now (text changed, a cited Microsoft page changed, or the check is old).
      due: pages.filter((p) => p.data.verification && verificationDue(p.data, Date.now(), { body: p.body, sourceChangedAt: sourceChanges.get(p.slug) || null })).length,
      recheckDays: VERIFICATION.recheckDays,
      cleanPasses: VERIFICATION.cleanPasses,
      settledRecheckDays: VERIFICATION.settledRecheckDays,
      sourcesWatched: Object.keys(sources.sources || {}).length,
      sourcesChecked: sources.generated,
    },
    messageCenter: {
      posts: messages.count || 0,
      actBy: deadlines.length,
      withheld: messages.screen?.withheld || 0,
      linked: (messages.posts || []).filter((m) => (m.roadmapIds || []).some((id) => briefedIds.has(id))).length,
    },
  };
  await writeJson(path.join(DATA_DIR, 'stats.json'), stats);
  const line = `- ${today()} index: ${pages.length} briefings, ${archived.length} archived, ${concepts.length} concepts indexed`;
  await appendLog(line);
  console.log(line);
}

main().catch((err) => { console.error(err); process.exit(1); });
